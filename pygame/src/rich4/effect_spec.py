# ◑ 导入
from dataclasses import dataclass
from enum import IntEnum

from rich4.game_types import 效果_类, 效果种类_类


# ◕ 功能
class 演员模式_类(IntEnum):
    """
    电影提交帧之前/之后人物采用世界、离开、停留、到达或隐藏状态。

    更新日志：
    2026.10.24 - 保留原Actor顺序。
    """

    世界, 离开, 停留, 到达, 隐藏 = range(5)


@dataclass(frozen=True)
class 演出规格_类:
    """
    原电影资源、提交/声音帧、停留/相机和演员覆盖参数。

    更新日志：
    2026.10.24 - 无电影不等于无效果；抛物和神明离开由独立精灵时序绘制。
    """

    库: str = "d"
    资源: int = -1
    提交帧: int = 0
    声音: int = -1
    声音帧: int = 0
    停留毫秒: int = 0
    相机目标: bool = True
    x: int = 0
    y: int = 40
    演员: 演员模式_类 = 演员模式_类.世界
    受伤: bool = False
    保留末帧: bool = False

    @classmethod
    def api_查询(cls, arg_效果: 效果_类) -> "演出规格_类":
        k, 物 = arg_效果.种类, arg_效果.物件种类
        简表 = {
            效果种类_类.顶楼闪光: (523, 0, 90, 0),
            效果种类_类.免费建设: (553, 44, 91, 0),
            效果种类_类.飞弹: (528, 9, 81, 0),
            效果种类_类.核弹: (530, 9, 83, 0),
            效果种类_类.爆炸: (525, 3, 82, 0),
            效果种类_类.拆屋: (529, 38, 97, 500),
            效果种类_类.怪兽: (557, 16, 80, 500),
            效果种类_类.破产: (555, 0, 100, 0),
            效果种类_类.狗撞车: (552, 1, 85, 0),
        }
        if k in 简表:
            条, 帧, 声, 停 = 简表[k]
            return cls("d", 条, 帧, 声, 0, 停)
        if k in (
            效果种类_类.掷骰,
            效果种类_类.金额转盘,
            效果种类_类.轮盘,
            效果种类_类.股利,
            效果种类_类.彩票开奖,
            效果种类_类.月报,
            效果种类_类.暂停,
        ):
            return cls("p", 相机目标=False)
        if k == 效果种类_类.抛物:
            return cls("d", -1, 0, 33 if 物 == 16 else 34 if 物 == 17 else 10, 0, 100, False)
        if k == 效果种类_类.神明出现:
            神明 = {
                1: (540, 102),
                2: (541, 103),
                3: (542, 104),
                4: (543, 105),
                5: (544, 106),
                6: (545, 107),
                7: (546, 108),
                8: (547, 109),
                9: (548, 110),
                10: (549, 112),
                12: (550, 111),
                15: (551, 113),
            }
            if 物 in 神明:
                条, 声 = 神明[物]
                return cls("d", 条, 0, 声, 保留末帧=True)
            return cls()
        if k == 效果种类_类.恶魔烟:
            return cls("d", 526, 3, 95, 相机目标=False)
        if k == 效果种类_类.救护车:
            return cls("d", 524, 30, 92, y=210, 演员=演员模式_类.离开, 受伤=True)
        if k == 效果种类_类.警车:
            return cls("d", 538, 18, 94, 演员=演员模式_类.离开)
        if k == 效果种类_类.狗打架:
            return cls("d", 532, 3, 93, 演员=演员模式_类.停留, 受伤=True)
        if k in (效果种类_类.飞碟, 效果种类_类.飞机):
            条, 帧, 声 = (533, 28, 84) if k == 效果种类_类.飞碟 else (558, 20, 96)
            return cls("d", 条, 帧, 声, 演员=演员模式_类.到达 if 物 else 演员模式_类.离开)
        if k == 效果种类_类.降落伞:
            return cls("d", 559 + min(物, 11), 演员=演员模式_类.隐藏)
        if k == 效果种类_类.新闻影片:
            新 = {
                4: (531, 24, 86),
                5: (539, 32, 84),
                15: (527, 5, 87),
                20: (534, 8, 89),
                21: (535, 8, 88),
            }
            if 物 in 新:
                条, 帧, 声 = 新[物]
                return cls("d", 条, 帧, 声)
            return cls()
        if k == 效果种类_类.抛卡:
            return cls("d", 停留毫秒=100, 相机目标=False)
        if k == 效果种类_类.问号箱:
            return cls("d", 536, 0, 99, 相机目标=False, x=208, y=180)
        if k == 效果种类_类.点券:
            return cls("d", 537, 0, 98, 相机目标=False, x=204, y=180)
        if k == 效果种类_类.工程车拆屋:
            return cls("d", 526, 0, 15, 相机目标=False)
        if k == 效果种类_类.节日烟花:
            return cls("d", 523, 0, 90, 相机目标=False)
        if k == 效果种类_类.圣诞:
            return cls("d", 554, 0, 114, 相机目标=False)
        if k == 效果种类_类.神明离开:
            return cls("d", 相机目标=False)
        return cls()
