def test_买方道具上限拒绝且地产建筑变化使旧卖单失效() -> None:
    世 = 交易样本()
    assert 交易_类.api_挂牌(世, 0, 挂单_类(货类_类.道具, 1, 1234)).已应用
    世.玩家[1].记录.道具[0] = 9
    assert not 交易_类.api_购买(世, 1, 0, 0).已应用
    assert 世.玩家[0].记录.道具[0] == 1
    世.玩家[1].记录.道具[0] = 8
    assert 交易_类.api_购买(世, 1, 0, 0).已应用
    assert 世.玩家[1].记录.道具[0] == 9 and 世.道具供应[0] == 10
    assert 交易_类.api_挂牌(世, 0, 挂单_类(货类_类.地产, 2001, 1234)).已应用
    世.地产[1].经济.等级 += 1
    assert not 交易_类.api_购买(世, 1, 0, 0).已应用
    assert 交易_类.api_清理(世) == 1


def test_电脑空市场仍三次门控抽取而不活跃者不抽取() -> None:
    世 = 交易样本()
    for 玩家 in 世.玩家:
        玩家.记录.卡片[:] = [0] * 15
        玩家.记录.道具[:] = [0] * 15
    随机, 预期 = 随机数_类(7), 随机数_类(7)
    for _ in range(3):
        预期.api_下一个()
    交易_类.api_电脑回合(世, 随机, 0)
    assert 随机.状态 == 预期.状态
    世.玩家[0].记录.控制标志 = 0
    交易_类.api_电脑回合(世, 随机, 0)
    assert 随机.状态 == 预期.状态


def test_道具供应255回绕后接收失败但仍按源代码结算() -> None:
    世 = 交易样本()
    世.道具供应[0] = 255
    世.玩家[1].记录.道具[0] = 0
    assert 交易_类.api_挂牌(世, 0, 挂单_类(货类_类.道具, 1, 1)).已应用
    assert 交易_类.api_购买(世, 1, 0, 0).已应用
    assert 世.道具供应[0] == 0
    assert 世.玩家[0].记录.道具[0] == 世.玩家[1].记录.道具[0] == 0
    assert (世.玩家[1].记录.现金, 世.玩家[0].记录.银行) == (99999, 10001)
