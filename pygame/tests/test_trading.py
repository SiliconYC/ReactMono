# ◕ 功能
def 位(arg_数: float) -> int:
    return struct.unpack("<I", struct.pack("<f", arg_数))[0]


def 交易样本() -> 世界_类:
    世 = 世界_类.api_从地图(合成地图())
    世.头.物价 = 2
    for i, 玩家 in enumerate(世.玩家):
        玩家.记录.控制标志 = 2
        玩家.记录.现金, 玩家.记录.银行 = 100000, 10000
        玩家.记录.卡片[:] = [1, 3, 5, 7, 9] + [0] * 10
        玩家.记录.道具[:13] = [1, 2, 3, 1, 2, 3, 1, 2, 3, 1, 2, 3, 1]
        for 股 in 玩家.持仓:
            股.数量, 股.成本位 = 100 + i, 位(12.375)
    世.地产[1].经济.业主 = 1
    世.地产[1].经济.等级 = 2
    世.地产[1].地价, 世.地产[1].每级造价 = 1000, 500
    世.地产[1].到期日 = 0x07EB0101
    世.设施[:] = [设施_类(), 设施_类(编号=1, 地价=2000, 业主=1, 类型=2, 等级=3)]
    世.设施[1].每级造价 = 700
    for 股 in 世.股票:
        股.浮点位[2], 股.可购股数 = 位(20.25), 777
    世.卡供应[:] = [3] * 30
    世.道具供应[:] = [10] * 8
    return 世


def test_挂牌参考价及闲置字段不变库存不预留() -> None:
    世 = 交易样本()
    assert 交易_类.api_限价(世, 0, 货类_类.股票, 2, 99).参考价 == 2004
    assert 交易_类.api_限价(世, 0, 货类_类.地产, 2001).参考价 == 4000
    assert 交易_类.api_限价(世, 0, 货类_类.地产, 4001).参考价 == 8200
    assert 交易_类.api_限价(世, 1, 货类_类.地产, 4001) is None
    项 = 世.出售表[0][0]
    项.数量, 项.地产类型, 项.地产等级 = 4321, 77, 88
    原卡 = 世.玩家[0].记录.卡片.copy()
    assert 交易_类.api_挂牌(世, 0, 挂单_类(货类_类.卡片, 3, 111)).已应用
    assert 世.玩家[0].记录.卡片 == 原卡
    assert (项.数量, 项.地产类型, 项.地产等级) == (4321, 77, 88)
    assert 交易_类.api_挂牌(世, 0, 挂单_类(货类_类.卡片, 3, 222)).已应用
    assert len(交易_类.api_报价(世)) == 1


def test_清理删除标志冻结游标下次才清后续失效项() -> None:
    世 = 交易样本()
    for 物 in (1, 2, 3):
        assert 交易_类.api_挂牌(世, 0, 挂单_类(货类_类.道具, 物, 100)).已应用
    世.玩家[0].记录.道具[0] = 世.玩家[0].记录.道具[2] = 0
    assert 交易_类.api_清理(世) == 1
    assert [项.项目 for 项 in 世.出售表[0][:2]] == [2, 3]
    assert len(交易_类.api_报价(世)) == 1
    assert 交易_类.api_清理(世) == 1
    assert 世.出售表[0][1].种类 == 0


def test_卡交易现金付银行收并压紧手牌共享供应不变() -> None:
    世 = 交易样本()
    assert 交易_类.api_挂牌(世, 0, 挂单_类(货类_类.卡片, 3, 1234)).已应用
    assert 交易_类.api_购买(世, 1, 0, 0).已应用
    assert (世.玩家[1].记录.现金, 世.玩家[0].记录.银行) == (98766, 11234)
    assert 世.玩家[0].状态.累计收入 == 世.玩家[1].状态.累计支出 == 1234
    assert 世.玩家[0].记录.卡片[:5] == [1, 5, 7, 9, 0]
    assert 世.玩家[1].记录.卡片[5] == 3 and 世.卡供应[2] == 3


