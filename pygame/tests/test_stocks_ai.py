# ◕ 功能
def 股票电脑样本() -> 世界_类:
    世 = 服务样本()
    世.头.日期, 世.头.物价, 世.股史游标 = (1, 1, 2000), 1, 0
    for 人 in 世.玩家:
        人.记录.现金, 人.记录.银行, 人.记录.贷款 = 0, 100000, 0
        人.状态.股票投资比例 = 80
        for 持 in 人.持仓:
            持.数量, 持.成本位 = 0, 0
    for 股 in 世.股票:
        股.标志4, 股.标志10, 股.可购股数, 股.停牌天数 = 0, 0, 1000, 0
        股.浮点位[:] = [股市_类._位(20), 股市_类._位(10), 股市_类._位(10), 0, 股市_类._位(1)]
    for 历 in 世.股史:
        历[:] = [股市_类._位(5)] * 144
    股 = 世.股票[0]
    股.标志4, 股.标志10 = 1, 1000
    司 = 世.公司[1]
    司.股票索引, 司.业主, 司.资金, 司.资金变化, 司.估值 = 0, 0, 10000, 10000, 1000000
    世.月数 = 1
    return 世


def test_校验在随机之前且关闭或零比例仍抽概率() -> None:
    世, 随机 = 股票电脑样本(), 随机数_类(0)
    世.股史游标 = 144
    with pytest.raises(ValueError):
        股票电脑_类.api_买入(世, 随机, 0, True)
    assert 随机.状态 == 0
    世.股史游标 = 0
    assert 股票电脑_类.api_买入(世, 随机, 0, True) == []
    assert 随机.状态 == 12345
    随机.状态 = 0
    世.玩家[0].状态.股票投资比例 = 0
    assert 股票电脑_类.api_买入(世, 随机, 0, False) == [] and 随机.状态 == 12345


def test_公司低价买入完整结算且只买一股种() -> None:
    世, 随机 = 股票电脑样本(), 随机数_类(0)
    成交 = 股票电脑_类.api_买入(世, 随机, 0, False)
    assert len(成交) == 1 and (成交[0].股票, 成交[0].数量, 成交[0].金额) == (0, 1000, 10000)
    assert 世.玩家[0].记录.银行 == 90000 and 世.玩家[0].持仓[0].数量 == 1000
    assert 随机.状态 == 3554416254


def test_紧急贷款卖出跳过概率抽样并入银行() -> None:
    世, 随机 = 股票电脑样本(), 随机数_类(17)
    人 = 世.玩家[0]
    人.记录.银行, 人.记录.贷款, 人.状态.贷款到期 = 0, 1000, 0
    人.持仓[0].数量, 人.持仓[0].成本位 = 10, 股市_类._位(5)
    成交 = 股票电脑_类.api_卖出(世, 随机, 0, False)
    assert [(项.股票, 项.数量, 项.金额) for 项 in 成交] == [(0, 10, 100)]
    assert 人.记录.银行 == 100 and 人.持仓[0].数量 == 0 and 随机.状态 == 17


def test_紧急休市不抽随机而非紧急休市仍抽一次() -> None:
    世, 随机 = 股票电脑样本(), 随机数_类(17)
    世.玩家[0].记录.银行, 世.玩家[0].记录.贷款 = 0, 1000
    assert 股票电脑_类.api_卖出(世, 随机, 0, True) == [] and 随机.状态 == 17
    世.玩家[0].记录.银行 = 100000
    assert 股票电脑_类.api_卖出(世, 随机, 0, True) == [] and 随机.状态 != 17


def test_打包到期日保留十一月三十一并把零解释为负一() -> None:
    assert 股票电脑_类._原日序(0) == -1
    assert 股票电脑_类._原日序(2000 << 16 | 11 << 8 | 31) == 股票电脑_类._原日序(
        2000 << 16 | 12 << 8 | 1
    )


def test_历史均值忽略正负零且逐次落单精度() -> None:
    世 = 股票电脑样本()
    世.股史[0][:] = [0] * 144
    世.股史[0][138:144] = [0, 0x80000000, 股市_类._位(3), 股市_类._位(7), 0, 0]
    assert 股票电脑_类._历史均值(世, 0, 6) == 5.0


def test_原排序不能替换为稳定分数排序() -> None:
    项 = [(i, 0) for i in range(12)]
    项[6] = (6, 1)
    股票电脑_类._原排序(项)
    assert 项[0] == (6, 1)
    assert [i for i, 分 in 项 if 分 == 0] == [1, 2, 0, 4, 5, 3, 7, 8, 9, 10, 11]


def test_零成本无限比率按原不定整数和回绕而非跳过() -> None:
    世 = 股票电脑样本()
    世.股票[0].标志4 = 0
    世.玩家[0].记录.银行 = 0
    世.玩家[0].持仓[0].数量 = 1
    assert 股票电脑_类._比率分(float("inf"), 0) == -2147483648
    assert 股票电脑_类._市场卖分(世, 0, 0, True) == 0
