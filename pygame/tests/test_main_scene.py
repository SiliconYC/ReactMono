def test_行走负方向向零截断并让附身物件跟随当前坐标与方向() -> None:
    会, 屏, 播 = 会话样本(), 主屏幕_类(), 电影播放_类(美术_类(Path("unused")))
    会.动画 = 移动动画_类(0, 100, 100, 67, 132, 80, 160)
    会.世界.物件[-1].种类, 会.世界.物件[-1].附身玩家 = 18, 1
    原, 随 = 会.世界.api_导出(), 会.随机.状态
    场, 相 = 主板场景_类.api_构建(会, 屏, 播, [], False, None, 0, 240)
    人 = next(p for p in 场.玩家 if p.槽位 == 0)
    assert 人.位置 == (84, 116) and 人.走动 and 人.动画帧 == 2
    assert 人.方向 == 方向_类.api_计算(-33, 32)
    物 = next(o for o in 场.物件 if o.跟随)
    assert 物.位置 == 人.位置 and 物.方向 == 人.方向
    assert 相.中心 == 人.位置
    assert 会.世界.api_导出() == 原 and 会.随机.状态 == 随


def test_尚待运输旧位置及说话者相机优先于自由相机和目标相机() -> None:
    会, 屏, 播 = 会话样本(), 主屏幕_类(), 电影播放_类(美术_类(Path("unused")))
    会.世界.玩家[0].状态.医院天数 = 3
    屏._自由中心 = (400, 400)
    会.待决策 = 决策_类(决策种类_类.卡片目标, 0)
    步 = [表现步_类(效果=效果_类(效果种类_类.救护车, 玩家=0, 起点=效果点_类(75, 125)))]
    场, 相 = 主板场景_类.api_构建(会, 屏, 播, 步, False, 0, 3, 0, (500, 500), 0)
    assert 场.玩家[-1].位置 == (75, 125) and 场.玩家[-1].活跃
    assert 相.中心 == (75, 125) and 相.旋转 == 3
    assert 播._待播人物[0].位置 == (75, 125)


def test_未呈现买地与两次升级按逆序显示旧业主和旧等级而不改世界() -> None:
    会, 屏, 播 = 会话样本(), 主屏幕_类(), 电影播放_类(美术_类(Path("unused")))
    世 = 会.世界
    世.节点[1].类型索引 = 2001
    世.地产[1].经济.业主, 世.地产[1].经济.等级 = 2, 3
    步 = [
        表现步_类(事件=游戏事件_类(k, 0, 节点=1))
        for k in (游戏事件种类_类.已购地, 游戏事件种类_类.已升级, 游戏事件种类_类.已升级)
    ]
    场, _ = 主板场景_类.api_构建(会, 屏, 播, 步, False, 0, 0, 0)
    assert (场.地产[0].业主, 场.地产[0].等级) == (0, 1)
    assert (世.地产[1].经济.业主, 世.地产[1].经济.等级) == (2, 3)


def test_待抛物在场景隐藏而附身物件不被隐藏且显示玩家零有效() -> None:
    会, 屏, 播 = 会话样本(), 主屏幕_类(), 电影播放_类(美术_类(Path("unused")))
    物 = 会.世界.物件[-1]
    物.种类, 物.节点, 物.附身玩家 = 16, 1, 0
    点 = 会.世界.节点[1]
    步 = [表现步_类(效果=效果_类(效果种类_类.抛物, 目标=效果点_类(点.x, 点.y), 物件种类=16))]
    场, _ = 主板场景_类.api_构建(会, 屏, 播, 步, False, 0, 0, 0)
    assert not any(o.种类 == 16 and not o.跟随 for o in 场.物件)
    assert 屏._显示玩家 == 0
    物.附身玩家 = 1
    场, _ = 主板场景_类.api_构建(会, 屏, 播, [], True, 0, 0, 0)
    assert any(o.种类 == 16 and o.跟随 for o in 场.物件)
