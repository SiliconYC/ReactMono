import pytest
from test_world import 合成地图

from rich4.lottery import 彩票_类, 彩票状态错误_类, 购票结果_类
from rich4.random import 随机数_类
from rich4.world import 世界_类


# ◕ 功能
def test_人工可以买最后一千电脑必须有多余且无抽取不耗随机数() -> None:
    世 = 世界_类.api_从地图(合成地图())
    世.玩家[0].记录.现金 = 1000
    世.头.物价 = 99
    世.公共基金 = 2147482648
    随机 = 随机数_类(0)
    assert 彩票_类.api_随机购票(世, 随机, 0) is None and 随机.状态 == 0
    assert 彩票_类.api_购票(世, 0, 36) == 购票结果_类.成功
    assert 世.玩家[0].记录.现金 == 0 and 世.公共基金 == -2147483648
    assert 世.玩家[0].状态.累计支出 == 0
    assert 彩票_类.api_购票(世, 1, 36) == 购票结果_类.已售出
    assert 彩票_类.api_购票(世, 0, 1) == 购票结果_类.现金不足
    世.玩家[1].记录.现金 = 1001
    世.彩票[:] = [1] * 36
    世.彩票[14] = 0
    assert 彩票_类.api_随机购票(世, 随机, 1) == 15
    assert 随机.状态 == 12345 and 世.玩家[1].记录.现金 == 1
    世.玩家[1].记录.现金 = 5000
    assert 彩票_类.api_随机购票(世, 随机, 1) is None and 随机.状态 == 12345


def test_流奖保留票与基金中奖清空且收入回绕() -> None:
    世 = 世界_类.api_从地图(合成地图())
    世.公共基金 = 15000
    随机 = 随机数_类(0)
    assert not 彩票_类.api_开奖(世, 随机).已开奖 and 随机.状态 == 0
    世.彩票[1] = 1
    结果 = 彩票_类.api_开奖(世, 随机)
    assert 结果.已开奖 and 结果.号码 == 1 and 结果.赢家 is None
    assert 世.彩票[1] == 1 and 世.公共基金 == 15000
    世.彩票[0] = 2
    世.玩家[1].记录.现金 = 2147483647
    世.玩家[1].状态.累计收入 = 0xFFFFFFF0
    结果 = 彩票_类.api_开奖(世, 随机数_类(0))
    assert (结果.赢家, 结果.奖金, 结果.仅售出票) == (1, 15000, False)
    assert 世.玩家[1].记录.现金 == -2147468649
    assert 世.玩家[1].状态.累计收入 == 14984
    assert 世.公共基金 == 0 and not any(世.彩票)


def test_保证中奖是任一玩家超过十张而非总数() -> None:
    世 = 世界_类.api_从地图(合成地图())
    世.彩票[:] = [0] * 10 + [1] * 10 + [0] * 16
    assert not 彩票_类.api_开奖(世, 随机数_类(0)).仅售出票
    世.彩票[20] = 1
    世.彩票[30] = 3
    结果 = 彩票_类.api_开奖(世, 随机数_类(0))
    assert (结果.仅售出票, 结果.号码, 结果.赢家) == (True, 11, 0)
    世.彩票[:] = [1] * 10 + [2] * 10 + [0] * 16
    assert not 彩票_类.api_开奖(世, 随机数_类(1)).仅售出票


def test_破产退票不退费非法所有者拒绝开奖() -> None:
    世 = 世界_类.api_从地图(合成地图())
    世.彩票[:2] = [1, 2]
    世.公共基金 = 2000
    彩票_类.api_退票(世, 0)
    assert 世.彩票[:2] == [0, 2] and 世.公共基金 == 2000
    世.玩家[2].记录.控制标志 = 0
    assert 彩票_类.api_购票(世, 2, 3) == 购票结果_类.玩家未活跃
    for 号 in (0, 37):
        with pytest.raises(IndexError):
            彩票_类.api_购票(世, 1, 号)
    世.彩票[0] = 5
    with pytest.raises(彩票状态错误_类):
        彩票_类.api_可售号码(世)
    assert 彩票_类.api_开奖日((15, 10, 2026))
    assert not 彩票_类.api_开奖日((14, 10, 2026))
