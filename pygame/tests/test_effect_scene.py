def test_原棋盘判定允许仅y非零和任意控制标志并保留0x20覆盖() -> None:
    世 = 服务样本()
    人 = 世.玩家[0]
    人.记录.x, 人.记录.y, 人.记录.控制标志 = 0, 20, 0x80
    assert 演出场景_类.api_在棋盘(世, 0)
    人.状态.监狱天数 = 2
    assert not 演出场景_类.api_在棋盘(世, 0)
    人.记录.控制标志 |= 0x20
    assert 演出场景_类.api_在棋盘(世, 0)
    assert not 演出场景_类.api_在棋盘(世, 999)


def test_携带物件跟随已绘制人物的插值坐标方向且不会显示隐藏载体() -> None:
    世 = 服务样本()
    世.物件 = [地图物件_类(种类=18, 附身玩家=1), 地图物件_类(种类=2, 附身玩家=2)]
    世.玩家[0].状态.神明信息 = 1
    人 = 玩家精灵_类(位置=(123, 456), 方向=7, 槽位=0)
    组 = 演出场景_类.api_物件(世, [人], 5)
    assert len(组) == 1
    assert (组[0].位置, 组[0].方向, 组[0].跟随, 组[0].动画帧) == ((123, 456), 7, 2, 5)


def test_隐藏抛物只观察未附身项并原位修改列表() -> None:
    组 = [物件精灵_类(种类=16), 物件精灵_类(种类=18, 跟随=1)]
    观察 = []

    def 隐藏(arg_位: tuple[int, int], arg_种: int) -> bool:
        观察.append(arg_种)
        return True

    演出场景_类.api_隐藏物件(组, 隐藏)
    assert [o.种类 for o in 组] == [18] and 观察 == [16]


def test_同玩家首个待播电影决定旧位置并保留受伤服装() -> None:
    世, 待 = 服务样本(), []
    演出场景_类.api_加入待播(待, 效果_类(效果种类_类.救护车, 起点=效果点_类(4, 8)))
    演出场景_类.api_加入待播(待, 效果_类(效果种类_类.飞机, 物件种类=1))
    人 = 玩家精灵_类(位置=(99, 99), 槽位=0, 走动=True, 投骰=True, 踩水=True)
    组 = [人]
    演出场景_类.api_应用待播(组, 世, 待, 2, (18, 0, 0, 0))
    assert len(待) == len(组) == 1
    assert 组[0].位置 == (4, 8) and 组[0].受伤 and not 组[0].走动 and not 组[0].投骰
    assert 人.位置 == (99, 99) and 人.走动


def test_原电影表的到达离开神明停留与新闻提交帧() -> None:
    规 = 演出规格_类.api_查询(效果_类(效果种类_类.飞碟, 物件种类=1))
    assert (规.演员, 规.提交帧, 规.资源) == (演员模式_类.到达, 28, 533)
    神 = 演出规格_类.api_查询(效果_类(效果种类_类.神明出现, 物件种类=15))
    assert 神.保留末帧 and (神.资源, 神.声音) == (551, 113)
    新 = 演出规格_类.api_查询(效果_类(效果种类_类.新闻影片, 物件种类=20))
    assert (新.资源, 新.提交帧, 新.声音) == (534, 8, 89)


def test_静止快照数值独立并按原uint64时钟生成帧() -> None:
    世 = 服务样本()
    记 = 世.玩家[0].记录
    记.x, 记.y, 记.控制标志 = 30, 40, 1
    for 名 in ("酒店天数", "消失天数", "监狱天数", "医院天数"):
        setattr(世.玩家[0].状态, 名, 0)
    场 = 演出场景_类.api_静止快照(世, 18446744073709551615, (18, 0, 0, 0))
    assert 场.玩家[0].动画帧 == (18446744073709551615 // 120) % 6
    assert 场.玩家[0].特殊姿态 == 18
    旧 = 世.地产[1].经济.业主
    场.玩家[0].位置, 场.地产[0].业主 = (1, 2), 99
    assert (记.x, 记.y, 世.地产[1].经济.业主) == (30, 40, 旧)
