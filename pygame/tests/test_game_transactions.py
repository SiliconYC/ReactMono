# ◕ 功能
class 事务样本_类(会话事务_类):
    """
    事务专属测试适配器，使用真实世界，不提供正式会话的替代规则。

    更新日志：
    2026.10.24 - 只观察源事务调用的阶段/结束/不支持接口。
    """

    def __init__(self) -> None:
        self.世界, self.随机 = 服务样本(), 随机数_类(1)
        self.阶段, self.阶段毫秒 = 游戏阶段_类.移动, 99
        self.卡片电脑记忆 = 电脑卡片记忆_类(5, 6, 7)
        self.事件队列, self.效果队列 = [], []
        self.事件选择, self.选择随机状态 = {}, {}
        self.待续, self.待选择键, self.待决策 = None, 0, None
        self.选择序列, self.结束次数, self.不支持记录 = 99, 0, []

    def _结束回合(self) -> None:
        self.结束次数 += 1
        self.阶段 = 游戏阶段_类.推进回合

    def _置阶段(self, arg_阶段: 游戏阶段_类) -> None:
        self.阶段, self.阶段毫秒 = arg_阶段, 0

    def _不支持(self, arg_消息: str, arg_恢复: 游戏阶段_类) -> None:
        self.不支持记录.append((arg_消息, arg_恢复))


def 事件(arg_消息: str) -> 游戏事件_类:
    return 游戏事件_类(游戏事件种类_类.提示, 0, 消息=arg_消息)


def test_等待选择回滚规则随机与记忆但保留前置表现() -> None:
    会 = 事务样本_类()
    原 = 会.世界.api_导出()

    def 动作() -> None:
        会.世界.玩家[0].记录.现金 -= 100
        会.随机.api_下一个()
        会.卡片电脑记忆.参数0 = 55
        会.事件队列.append(事件("前置"))
        会.效果队列.append(效果_类(效果种类_类.爆炸, 事件位=1))
        raise 待选择异常_类(决策_类(决策种类_类.选择卡片, 0), 7)

    会._执行规则(动作)
    assert 会.世界.api_导出() == 原 and 会.随机.状态 == 1
    assert 会.卡片电脑记忆 == 电脑卡片记忆_类(5, 6, 7)
    assert 会.阶段 == 游戏阶段_类.等待决策 and 会.待选择键 == 7 and 会.待续 is not None
    assert 会.事件队列 == [事件("前置")] and 会.效果队列[0].事件位 == 1


def test_两次嵌套选择重放不重复扣款随机或已展示效果() -> None:
    会 = 事务样本_类()
    原额, 成功 = 会.世界.玩家[0].记录.现金, []

    def 动作() -> None:
        会.世界.玩家[0].记录.现金 -= 100
        会.随机.api_下一个()
        会.事件队列.append(事件("A"))
        会.效果队列.append(效果_类(效果种类_类.怪兽, 事件位=len(会.事件队列)))
        if 1 not in 会.事件选择:
            raise 待选择异常_类(决策_类(决策种类_类.卡片目标, 0), 1)
        会.世界.玩家[0].记录.现金 -= 会.事件选择[1]
        会.事件队列.append(事件("B"))
        if 2 not in 会.事件选择:
            raise 待选择异常_类(决策_类(决策种类_类.选择卡片, 0), 2)
        会.世界.玩家[0].记录.现金 -= 会.事件选择[2]
        会.事件队列.append(事件("C"))

    会._执行规则(动作, arg_成功=lambda: 成功.append(True))
    assert 会.世界.玩家[0].记录.现金 == 原额
    会.事件选择[1] = 20
    会.待续()
    assert 会.世界.玩家[0].记录.现金 == 原额 and 会.事件队列 == [事件("A"), 事件("B")]
    会.事件选择[2] = 30
    会.待续()
    assert 会.世界.玩家[0].记录.现金 == 原额 - 150 and 会.随机.状态 == 1103527590
    assert 会.事件队列 == [事件("A"), 事件("B"), 事件("C")]
    assert len(会.效果队列) == 1 and 成功 == [True] and 会.结束次数 == 1
    assert not 会.事件选择 and 会.待续 is None


def test_删除事件后按严格小于关系修正效果交错位置() -> None:
    会 = 事务样本_类()
    会.事件队列 = [事件("旧"), 事件("A"), 事件("新"), 事件("B")]
    会.效果队列 = [效果_类(效果种类_类.爆炸, 事件位=i) for i in (1, 2, 3, 4)]
    会._去重表现(1, 0, 已展示_类([事件("A"), 事件("B")]))
    assert 会.事件队列 == [事件("旧"), 事件("新")]
    assert [效.事件位 for 效 in 会.效果队列] == [1, 1, 2, 2]


