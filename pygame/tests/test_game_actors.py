# ◕ 功能
class 角色样本_类(会话角色_类, 金融样本_类):
    """
    接通实际金融和角色规则的测试适配器，尚非主游戏入口。

    更新日志：
    2026.10.24 - 随机节点、物件、防御、建筑与收容均调用真实移植。
    """


def test_同步附身仅同步状态明确引用的两个物件() -> None:
    会 = 角色样本_类()
    会._状态().神明信息, 会._状态().附身炸弹 = 1, 19
    会.世界.物件[1].附身玩家, 会.世界.物件[1].节点 = 1, 9
    会._同步附身(0)
    assert 会.世界.物件[0].节点 == 会.世界.物件[18].节点 == 会._玩家().节点
    assert 会.世界.物件[1].节点 == 9


def test_提早释放医院衣服优先并保留方向键状态() -> None:
    会 = 角色样本_类()
    会._状态().监狱天数 = 会._状态().医院天数 = 1
    会.世界.监狱名单[0] = 会.世界.医院名单[0] = 1
    会._清缺席(0)
    assert 会.服装[0] == 19 and 会.服装键[0] == 会._服装键(0)
    assert 会._状态().医院天数 == 会._状态().监狱天数 == 0
    assert 会.世界.医院名单[0] == 会.世界.监狱名单[0] == 0


def test_受伤按完整交通字节判非零但只有原低位车辆返还供应() -> None:
    会 = 角色样本_类()
    会._玩家().交通 = 128
    原 = 会.世界.道具供应[:]
    会._受伤(0)
    assert 会._玩家().交通 == 0 and 会._玩家().骰数 == 1
    assert 会.世界.道具供应 == 原 and 会._玩家().控制标志 & 0x40
    会._玩家().交通 = 129
    会._受伤(0)
    assert 会.世界.道具供应[4] == (原[4] + 1) & 255


def test_特殊人物收容零天也移除占用并完整清状态() -> None:
    会 = 角色样本_类()
    特 = 会.世界.特殊角色[0]
    特.节点, 特.标志, 特.睡眠天数 = 1, 255, 4
    会.世界.节点[1].标志 |= 0x1000
    会._收容(4, 0, True)
    assert 特.不活跃状态 == 2 and 特.标志 == 特.睡眠天数 == 0
    assert 会.世界.医院名单[4] == 1 and not 会.世界.节点[1].标志 & 0x1000


def test_已有收容按七位延长而不重建位置影片() -> None:
    会 = 角色样本_类()
    会._状态().医院天数 = 128
    会._收容(0, 3, True)
    assert 会._状态().医院天数 == 会._状态().冬眠总天数 == 3
    assert not any(效.种类 == 效果种类_类.救护车 for 效 in 会.效果队列)


def test_离场首次赔偿延长不再赔偿且保留原编码() -> None:
    会 = 角色样本_类()
    会._状态().保险天数 = 1
    会.世界.公司[1].类型 = 4
    会._消失(0, 3, 1)
    assert 会._状态().消失天数 == 67 and 会._玩家().现金 == 16000
    会._消失(0, 2, 1)
    assert 会._状态().消失天数 == 69 and 会._玩家().现金 == 16000
    assert 会._状态().冬眠总天数 == 3


def test_免罪卡自动优先于嫁祸卡并返供应() -> None:
    会 = 角色样本_类()
    会._玩家().卡片[:] = [19, 21] + [0] * 13
    原 = 会.世界.卡供应[20]
    assert 会._尝试防御卡(0) == -1
    assert 会._玩家().卡片[:2] == [19, 0] and 会.世界.卡供应[20] == (原 + 1) & 255
    assert 会.随机.状态 == 1


def test_人类免付等待真实选择且事务恢复后只消耗一张卡() -> None:
    会 = 角色样本_类()
    会._玩家().卡片[:2] = [20, 20]
    会._执行规则(lambda: 会._尝试免付卡(0, 1, 3000), arg_结束后=False)
    assert 会.阶段 == 游戏阶段_类.等待决策 and 会._玩家().卡片.count(20) == 2
    会.事件选择[会.待选择键] = 1
    会.待续()
    assert 会._玩家().卡片.count(20) == 1 and 会.事件队列[0].卡片 == 20


def test_受害者选卡按首次出现去重而每次先增加选择序列() -> None:
    会 = 角色样本_类()
    会.世界.玩家[1].记录.卡片[:4] = [3, 1, 3, 1]
    with pytest.raises(待选择异常_类) as 错:
        会._选择受害卡(0, 1)
    assert [项.值 for 项 in 错.value.决策.选项] == [3, 1, 0]
    assert 会.选择序列 == 100


def test_设施拆空释放全部旅馆的所有活跃住客() -> None:
    会 = 角色样本_类()
    会.世界.设施.append(设施_类(编号=1, 等级=1, 类型=1))
    for 人 in 会.世界.玩家:
        人.状态.酒店天数 = 2
    会._改建筑(4001, False)
    assert 会.世界.设施[1].等级 == 会.世界.设施[1].类型 == 0
    assert all(人.状态.酒店天数 == 128 for 人 in 会.世界.玩家)


def test_建筑选择挂起前不升级按答案实际建设() -> None:
    会 = 角色样本_类()
    会.世界.设施.append(设施_类(编号=1))
    with pytest.raises(待选择异常_类) as 错:
        会._改建筑(4001, True)
    assert 会.世界.设施[1].等级 == 0
    会.选择序列 = 错.value.键
    会.事件选择[错.value.键] = 3
    会._改建筑(4001, True)
    assert 会.世界.设施[1].等级 == 1 and 会.世界.设施[1].类型 == 3


def test_原随机空节点拒绝任何超字节候选先于抽随机() -> None:
    会 = 角色样本_类()
    while len(会.世界.节点) <= 256:
        节 = deepcopy(会.世界.节点[1])
        节.标志, 节.邻居[:] = 0, [1, 0, 0, 0]
        会.世界.节点.append(节)
    with pytest.raises(RuntimeError, match="byte range"):
        会._随机空节点()
    assert 会.随机.状态 == 1


def test_移除附身炸弹返库存且清原状态不影响其他神明() -> None:
    会 = 角色样本_类()
    物 = 会.世界.物件[18]
    物.种类, 物.附身玩家, 物.节点 = 18, 1, 1
    会._状态().附身炸弹, 会._状态().神明信息 = 19, 1
    原 = 会.世界.道具供应[3]
    会._移除物件(19)
    assert 会._状态().附身炸弹 == 物.节点 == 物.附身玩家 == 0
    assert 会._状态().神明信息 == 1 and 会.世界.道具供应[3] == (原 + 1) & 255
