# ◕ 功能
def 拍卖样本(arg_人数: int = 3) -> 世界_类:
    世 = 世界_类.api_从地图(合成地图())
    世.头.物价 = 1
    世.头.日期 = (31, 1, 2000)
    世.公共基金 = 0
    世.地产[1].地价 = 1000
    世.地产[1].经济.街道名 = b"road"
    世.设施[:] = [设施_类(), 设施_类(编号=1, 地价=2000)]
    for i, 玩家 in enumerate(世.玩家):
        玩家.记录.控制标志 = 1 if i < arg_人数 else 0
        玩家.记录.现金 = 100000
        玩家.记录.银行 = 50000
    return 世


def test_起价先截断再乘物价同额现金无资格状态高位也排除() -> None:
    世 = 拍卖样本(4)
    世.地产[1].地价 = 1001
    世.地产[1].经济.等级 = 3
    世.头.物价 = 2
    世.玩家[0].记录.现金 = 5004
    世.玩家[1].记录.现金 = 5003
    世.玩家[2].状态.医院天数 = 0x80
    随机 = 随机数_类(47)
    拍卖 = 拍卖会话_类(世, 随机, 2001)
    决策 = 拍卖.api_决策()
    assert 拍卖.起价 == 5004 and 决策 is not None
    assert (决策.玩家, 决策.已退出) == (3, 7)
    assert 随机.状态 == 47
    assert 拍卖.api_竞价(拍卖行动_类.加一百)
    assert 拍卖.已结束 and 拍卖.结果.赢家 == 3
    assert 世.玩家[3].记录.现金 == 94896 and 世.公共基金 == 5104


def test_加价清临时放弃永久退出保留空位只结算一次() -> None:
    世 = 拍卖样本()
    世.地产[1].经济.等级 = 2
    世.地产[1].临时状态 = 0x12
    拍卖 = 拍卖会话_类(世, 随机数_类(9), 2001)
    assert 拍卖.api_决策().玩家 == 2
    assert 拍卖.api_竞价(拍卖行动_类.放弃)
    assert 拍卖.api_决策().玩家 == 0
    assert 拍卖.api_竞价(拍卖行动_类.加一百)
    assert 拍卖.api_决策().玩家 == 1
    assert 拍卖.api_竞价(拍卖行动_类.退出)
    assert 拍卖.api_决策().玩家 == 2 and 拍卖.api_决策().已退出 == 2
    assert 拍卖.api_竞价(拍卖行动_类.放弃)
    assert 拍卖.已结束 and 拍卖.结果.赢家 == 0
    assert (世.玩家[0].记录.现金, 世.玩家[0].记录.银行) == (97900, 50000)
    assert 世.玩家[0].状态.累计支出 == 世.公共基金 == 2100
    assert (世.地产[1].经济.业主, 世.地产[1].经济.等级, 世.地产[1].临时状态) == (1, 2, 0x12)
    assert not 拍卖.api_竞价(拍卖行动_类.加一百)


def test_拒绝非法行动不前进全放弃不成交正好全部现金可加价() -> None:
    世 = 拍卖样本(2)
    世.玩家[0].记录.现金 = 世.玩家[1].记录.现金 = 1100
    世.地产[1].经济.业主 = 2
    随机 = 随机数_类(13)
    拍卖 = 拍卖会话_类(世, 随机, 2001)
    assert not 拍卖.api_竞价(拍卖行动_类.加五百)
    assert not 拍卖.api_竞价(7)
    assert 拍卖.价格 == 1000 and 拍卖.api_决策().玩家 == 1
    assert 拍卖.api_竞价(拍卖行动_类.放弃)
    assert 拍卖.api_竞价(拍卖行动_类.放弃)
    assert 拍卖.已结束 and 拍卖.结果.赢家 is None
    assert 世.地产[1].经济.业主 == 2 and 世.公共基金 == 0
    拍卖 = 拍卖会话_类(世, 随机, 2001, 0)
    assert 拍卖.api_竞价(拍卖行动_类.加一百)
    assert 世.玩家[1].记录.现金 == 0
    assert 世.玩家[0].记录.银行 == 51100 and 世.玩家[0].状态.累计收入 == 1100


def test_设施租期保留二月三十一日且转售不重启租期() -> None:
    世 = 拍卖样本(1)
    世.租约模式 = 5
    世.设施[1].类型 = 2
    世.设施[1].等级 = 3
    随机 = 随机数_类(1)
    拍卖 = 拍卖会话_类(世, 随机, 4001)
    assert 拍卖.起价 == 5000
    assert 拍卖.api_竞价(拍卖行动_类.加五百)
    assert 世.设施[1].到期日 == 0x07D0021F
    世.设施[1].业主 = 2
    世.设施[1].到期日 = 0x12345678
    拍卖 = 拍卖会话_类(世, 随机, 4001)
    assert 拍卖.api_竞价(拍卖行动_类.加一百)
    assert 世.设施[1].到期日 == 0x12345678


def test_单电脑两次估价抽取后竞价不再消费随机数() -> None:
    世 = 拍卖样本(1)
    世.玩家[0].记录.控制标志 = 2
    随机 = 随机数_类(1)
    拍卖 = 拍卖会话_类(世, 随机, 2001)
    assert 随机.状态 == 2524885223
    assert 拍卖.api_电脑上限(0) == 1308
    assert 拍卖.api_决策() is None
    assert 拍卖.api_推进() and 拍卖.已结束
    assert (拍卖.结果.赢家, 拍卖.结果.价格) == (0, 1100)
    assert 随机.状态 == 2524885223


def test_构造拒绝坏卖家或租期而显式零租期覆盖原模式() -> None:
    世, 随机 = 拍卖样本(1), 随机数_类(99)
    世.租约模式 = 6
    with pytest.raises(ValueError):
        拍卖会话_类(世, 随机, 2001)
    with pytest.raises(ValueError):
        拍卖会话_类(世, 随机, 2001, 4, 0)
    assert 随机.状态 == 99
    拍卖 = 拍卖会话_类(世, 随机, 2001, -1, 0)
    assert 拍卖.api_竞价(拍卖行动_类.加一百) and 世.地产[1].到期日 == 0


def test_两千场电脑拍卖终止而现金与公共基金守恒() -> None:
    for 种子 in range(1, 2001):
        世 = 拍卖样本(4)
        世.头.物价 = 种子 % 4 + 1
        世.地产[1].经济.等级 = 种子 % 6
        for i, 玩家 in enumerate(世.玩家):
            玩家.记录.控制标志 = 2
            玩家.记录.现金 = 2000 + 种子 * (i + 1)
        原 = sum(玩家.记录.现金 for 玩家 in 世.玩家)
        拍卖 = 拍卖会话_类(世, 随机数_类(种子), 2001)
        for _ in range(1000):
            if 拍卖.已结束:
                break
            assert 拍卖.api_推进()
        assert 拍卖.已结束
        assert all(玩家.记录.现金 >= 0 for 玩家 in 世.玩家)
        assert 原 == 世.公共基金 + sum(玩家.记录.现金 for 玩家 in 世.玩家)
