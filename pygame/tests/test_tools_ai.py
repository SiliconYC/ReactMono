# ◕ 功能
def 道具电脑样本() -> 世界_类:
    世 = 服务样本()
    for i, 人 in enumerate(世.玩家):
        人.记录.控制标志, 人.状态.卡片策略, 人.状态.救援策略 = 2, 2, 2
        人.记录.交通, 人.记录.节点, 人.记录.上次节点 = 0, 1, 4
        人.记录.x, 人.记录.y = 32 + i, 32
        人.记录.现金, 人.记录.银行 = 100000, 100000
        人.记录.道具[:] = [0] * 15
        人.状态.敌意[:] = [0] * 4
    for 节 in 世.节点:
        节.标志 = 0
    return 世


def test_非法输入与访问开关不抽随机() -> None:
    世, 随机 = 道具电脑样本(), 随机数_类(1)
    assert not 道具电脑_类.api_评估(世, 随机, 4, 1, 道具电脑回调_类()).支持
    assert not 道具电脑_类.api_评估(世, 随机, 0, 14, 道具电脑回调_类()).支持
    世.玩家[0].状态.卡片策略 = 0
    assert 道具电脑_类.api_选择(世, 随机, 0, 道具电脑回调_类()).决策 is None
    assert 随机.状态 == 1


def test_少于五种不随机起点且单种也尝试四次() -> None:
    世, 随机, 预期 = 道具电脑样本(), 随机数_类(1), 随机数_类(1)
    世.玩家[0].记录.道具[4] = 1
    for _ in range(4):
        assert 预期.api_下一个() % 4 != 0
    果 = 道具电脑_类.api_选择(世, 随机, 0, 道具电脑回调_类())
    assert 果.决策 is None and 随机.状态 == 预期.状态
    assert 世.玩家[0].记录.道具[4] == 1


