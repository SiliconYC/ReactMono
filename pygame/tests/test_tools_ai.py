def test_前瞻单路不抽随机而分岔即使后续拒绝仍消费() -> None:
    世, 随机 = 道具电脑样本(), 随机数_类(1)
    路 = 道具电脑_类._前瞻(世, 随机, 0, 4)
    assert 路.节点 == [2, 3, 4, 1] and not 路.经过路口 and 随机.状态 == 1
    世.节点[1].邻居[:] = [2, 3, 4, 0]
    路 = 道具电脑_类._前瞻(世, 随机, 0, 1)
    assert 路.经过路口 and 路.节点 == [2] and 随机.状态 == 1103527590


def test_选择缓冲覆盖而非或运算并按半开区域扫描() -> None:
    世 = 道具电脑样本()
    缓 = 选择缓冲_类(世, (100, 100))
    缓.api_插入((100, 100), 1)
    缓.api_插入((100, 100), 2)
    assert 缓.api_扫描() == [2] and 缓.api_扫描(0) == [] and 缓.api_扫描(1) == [2]
    缓.api_插入((100, 100), 0)
    assert 缓.api_扫描() == []


def test_最高敌意先于缺席过滤且回退单目标仍抽随机() -> None:
    世, 随机 = 道具电脑样本(), 随机数_类(1)
    世.玩家[0].状态.敌意[1] = 100
    世.玩家[1].状态.医院天数 = 128
    assert 道具电脑_类._敌手(世, 随机, 0) == 1 and 随机.状态 == 1
    世.玩家[0].状态.敌意[:] = [0, 0xFFFFFFFF, 0, 0]
    世.玩家[2].记录.控制标志 = 世.玩家[3].记录.控制标志 = 0
    assert 道具电脑_类._敌手(世, 随机, 0) == -1 and 随机.状态 == 1
    世.玩家[1].状态.医院天数 = 0
    assert 道具电脑_类._敌手(世, 随机, 0) == 1 and 随机.状态 == 1103527590


def test_飞弹保留显式所有权寄存器残值边界() -> None:
    世, 随机 = 道具电脑样本(), 随机数_类(1)
    世.玩家[0].状态.敌意[1] = 100
    世.玩家[1].记录.x = 世.玩家[1].记录.y = 4000
    地 = 世.地产[1]
    地.x = 地.y = 4000
    地.经济.业主 = 2
    钩 = 道具电脑回调_类(附近实例=lambda _: [0x8002], 所有权残值=lambda: 0)
