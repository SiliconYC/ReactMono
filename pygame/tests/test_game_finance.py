def test_公司可支付负资金且公共基金按有符号回绕() -> None:
    会 = 金融样本_类()
    会.世界.公共基金 = 2147483640
    assert 会._付款(101, -1, 100, 0) == 100
    assert 会.世界.公司[1].资金 == 会.世界.公司[1].资金变化 == -100
    assert 会.世界.公共基金 == -2147483556
    assert 会._付款(-100, -10, 0, 0) == 0


def test_不足付款先破产再记支出并仍向接收方入账() -> None:
    会 = 金融样本_类()
