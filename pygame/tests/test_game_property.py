# ◕ 功能
class 地产样本_类(会话地产_类, 移动样本_类):
    """
    针对购地/决策/费用计算的测试适配器，未代替实际主会话结算。

    更新日志：
    2026.10.24 - 待实现融资/防御时只观察调用参数。
    """

    def __init__(self) -> None:
        移动样本_类.__init__(self)
        self.付租调用, self.敌意调用 = [], []
        self.轮盘游标 = self.轮盘种类 = self.轮盘毫秒 = self.轮盘设施 = 0
        self.世界.设施.append(设施_类(编号=1, 地价=1000, 各级租金=[100, 200, 300, 400, 500, 600]))
        self._玩家().现金, self._玩家().银行, self._玩家().控制标志 = 100000, 10000, 1

    def _租约到期(self) -> int:
        return 0x07D00101

    def _选择付租者(
        self, arg_额: int, arg_主: int, arg_强制缺席: bool = False, arg_可免: bool = True
    ) -> tuple[int, int]:
        self.付租调用.append((arg_额, arg_主, arg_强制缺席, arg_可免))
        return arg_主, arg_额

    def _更新敌意(self, arg_从: int, arg_到: int, arg_额: int) -> None:
        self.敌意调用.append((arg_从, arg_到, arg_额))


def test_普通购地允许现金恰好相等并存原租期() -> None:
    会 = 地产样本_类()
    地 = 会.世界.地产[1]
    地.地价, 地.每级造价, 地.经济.等级, 地.经济.业主 = 1000, 500, 2, 0
    会._玩家().现金 = 2000
    会._普通地产(1)
    assert 会.待决策.种类 == 决策种类_类.购地 and 会.待决策.金额 == 2000
    会._购买地产(1, False)
    assert 会._玩家().现金 == 0 and 地.经济.业主 == 1 and 地.到期日 == 0x07D00101


def test_改建设施先改类型再神明否决而不扣款或升级() -> None:
    会 = 地产样本_类()
    设 = 会.世界.设施[1]
    设.业主, 设.等级, 会._状态().神明信息 = 1, 0, 7
    原 = 会._玩家().现金
    会._购买设施(1, 1, 4)
    assert 设.类型 == 4 and 设.等级 == 0 and 会._玩家().现金 == 原


def test_购地现金不足发原公告而负溢出价格不发() -> None:
    会 = 地产样本_类()
    地 = 会.世界.地产[1]
    地.地价, 地.经济.等级, 地.经济.业主 = 1000, 0, 0
    会._玩家().现金 = 999
    会._普通地产(1)
    assert 会.事件队列[-1].地产 == 2001
    会.事件队列.clear()
    会.世界.头.物价 = 2147483647
    会._普通地产(1)
    assert not 会.事件队列


def test_电脑购买储备门槛严格大于且资金求和不回绕() -> None:
    会 = 地产样本_类()
    会.世界.头.初始资金 = 100000
    会._玩家().现金, 会._玩家().银行 = 5000, 1000
    assert not 会._电脑可购买(1000)
    会._玩家().银行 += 1
    assert 会._电脑可购买(1000)
    会._玩家().现金 = 会._玩家().银行 = 2147483647
    assert 会._电脑可购买(2147483647)


