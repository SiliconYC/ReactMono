def test_目标编码可取消且实际选项保留位置和主体() -> None:
    会 = 动作样本_类()
    卡 = 卡片目标_类(目标种类_类.地产, 2001)
    with pytest.raises(待选择异常_类) as 错:
        会._选择目标([卡], "test", 1)
    assert 错.value.决策.选项[0].对象 == 卡
    assert 错.value.决策.选项[0].值 == (1 << 16) | 2001
    assert 错.value.决策.被抢玩家 == 1
    会.选择序列, 会.事件选择[错.value.键] = 错.value.键, -1
    assert 会._选择目标([卡], "test") is None


