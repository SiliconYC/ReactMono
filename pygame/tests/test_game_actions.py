# ◕ 功能
class 动作样本_类(会话动作_类, 角色样本_类):
    """
    动作边界与真实既有规则接线的测试适配器，不提供替代游戏。

    更新日志：
    2026.10.24 - 回调依赖使用真实角色、金融及事务模块。
    """

    def __init__(self) -> None:
        角色样本_类.__init__(self)
        self.地雷待处理 = False
        self.转盘随机, self.转盘毫秒, self.金钱转盘 = 随机数_类(0), 0, None


def test_会话选择缓冲同点按位合并而非电脑道具覆盖() -> None:
    会 = 动作样本_类()
    for i, 人 in enumerate(会.世界.玩家):
        人.记录.x, 人.记录.y = (1000, 1000) if i < 2 else (0, 0)
    for 公 in 会.世界.公司:
        公.精灵 = 0
    for 特 in 会.世界.特殊角色:
        特.x = 0
    assert 会._实例编码(1000, 1000, 1) == [0x8003]
    assert 会._实例编码(1000, 1000, 0) == []
    with pytest.raises(ValueError):
        会._实例编码(1000, 1000, 221)
    会.世界.相机旋转 = 8
    with pytest.raises(RuntimeError, match="rotation"):
        会._实例编码(1000, 1000, -1)


