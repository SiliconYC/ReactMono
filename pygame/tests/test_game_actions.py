def test_时光机原位恢复旧日期资金但保留当前玩家和相机不恢复随机() -> None:
    会 = 动作样本_类()
    旧 = deepcopy(会.世界)
    旧.头.日期, 旧.头.物价, 旧.头.初始资金 = (2, 2, 1999), 3, 8000
    会.上一回合[0], 会.世界.相机旋转, 会.世界.租约模式 = 旧, 6, 5
    会._玩家().现金, 会.随机.状态 = 8, 77
    引用 = 会.世界
    assert 会._恢复上次()
    assert 会.世界 is 引用 and 会._玩家().现金 == 10000
    assert 会.世界.头.当前玩家 == 0 and 会.世界.头.日期 == (2, 2, 1999)
    assert 会.世界.头.物价 == 3 and 会.世界.头.初始资金 == 8000
    assert (会.世界.相机旋转, 会.世界.租约模式, 会.随机.状态) == (6, 5, 77)


def test_机器人九次真实寻路单路径仍抽样但死路回退不抽样() -> None:
    会 = 动作样本_类()
    会.世界.节点[:] = [
        节点_类(),
        节点_类(1, 100, 100, [2, 0, 0, 0]),
        节点_类(2, 200, 100, [1, 3, 0, 0]),
        节点_类(3, 300, 100, [2, 0, 0, 0]),
    ]
    会._玩家().节点, 会._玩家().上次节点, 会._玩家().x, 会._玩家().y = 1, 2, 100, 100
    会._机器人(0)
    随 = 随机数_类(1)
    for _ in range(4):
        随.api_下一个()
    assert len(会.事件队列) == 9 and 会.随机.状态 == 随.状态
    assert 会.世界.特殊角色[4].节点 == 2 and 会.世界.特殊角色[4].不活跃状态 == 3
    assert not any(节.标志 for 节 in 会.世界.节点)


