def test_股票卡按成本选最高且电脑排除停牌() -> None:
    世, 随, 记 = 道具电脑样本(), 随机数_类(1), 电脑卡片记忆_类()
    for 股 in 世.股票:
        股.浮点位[1] = 股.浮点位[2] = 股市_类._位(100)
    for 持 in 世.玩家[0].持仓:
        持.数量, 持.成本位 = 0, 0
    持 = 世.玩家[0].持仓[2]
    持.数量, 持.成本位 = 100, 股市_类._位(20)
    钩 = 卡片回调_类(休市=lambda: False)
    assert 卡片电脑_类._谓词(世, 随, 0, 24, 钩, 记, 8) and 记.参数0 == 2
    世.股票[2].停牌天数 = 1
    assert not 卡片电脑_类._谓词(世, 随, 0, 24, 钩, 记, 8)


