def test_策略位和非法玩家不消费随机() -> None:
    世, 随 = 道具电脑样本(), 随机数_类(1)
    世.玩家[0].记录.卡片[:] = [15] + [0] * 14
    assert 卡片电脑_类.api_选择(世, 随, 0, 卡片回调_类()) is None
    assert 卡片电脑_类.api_选择(世, 随, 99, 卡片回调_类()) is None
    assert 随.状态 == 1


def test_主动访问不消耗手牌且保留未赋值参数() -> None:
    世, 随 = 道具电脑样本(), 随机数_类(0)
    人, 地 = 世.玩家[0], 世.地产[1]
    人.状态.卡片策略, 人.记录.节点 = 1, 1
    人.记录.卡片[:] = [14] + [0] * 14
    世.节点[1].类型索引 = 2001
    地.经济.业主, 地.经济.等级, 地.每级造价 = 1, 2, 100
    记 = 电脑卡片记忆_类(0x8002, 77, 88)
    果 = 卡片电脑_类.api_选择(世, 随, 0, 卡片回调_类(), 记)
    assert 果 is not None and 果.目标 is not None and 果.目标.数值 == 1
    assert 记 == 电脑卡片记忆_类(0x8002, 77, 88) and 人.记录.卡片[0] == 14


