def test_怪兽敌意设施优先并在无敌意时过滤三级普通地() -> None:
    世 = 道具电脑样本()
    世.地产[1].经济.业主, 世.地产[1].经济.等级 = 2, 5
    世.设施.append(设施_类(编号=1, 业主=2, 等级=3))
    世.玩家[0].状态.敌意[1] = 1
    assert 卡片电脑_类._怪兽(世, 0, [2001, 4001]) == 4001
    世.玩家[0].状态.敌意[1] = 0
    世.地产[1].经济.等级 = 3
    assert 卡片电脑_类._怪兽(世, 0, [2001]) == 0


