# ◕ 功能
def 浮点位(arg_值: float) -> int:
    return struct.unpack("<I", struct.pack("<f", arg_值))[0]


def 股市样本() -> 世界_类:
    世界 = 世界_类.api_从地图(合成地图())
    世界.股票[0].标志4 = 1
    世界.股票[0].可购股数 = 6600
    世界.股票[0].标志10 = 1500
    世界.股票[0].浮点位[2] = 浮点位(15.55)
    世界.公共基金 = 2000
    for i, 玩家 in enumerate(世界.玩家):
        玩家.记录.银行 = 10000
        玩家.记录.现金 = 20000
        玩家.持仓[0].数量 = 1000 - i * 100
        玩家.持仓[0].成本位 = 浮点位(21.25)
    世界.公司[1].股东排名[:] = [1, 2, 3, 4]
    世界.公司[1].业主 = 1
    return 世界


def test_卖股结算清成本与同持股优先顺序() -> None:
    世界 = 股市样本()
    结果 = 股市_类.api_卖出(世界, 0, 0, 1000, True)
    assert (结果.收入, 结果.公司易主) == (15550, True)
    assert (世界.玩家[0].记录.银行, 世界.玩家[0].记录.现金, 世界.公共基金) == (25550, 20000, 2000)
    assert (世界.玩家[0].持仓[0].数量, 世界.玩家[0].持仓[0].成本位) == (0, 0)
    assert 世界.公司[1].股东排名 == [2, 3, 4, 0]
    世界 = 股市样本()
    股市_类.api_卖出(世界, 0, 0, 100, False)
    assert 世界.公共基金 == 3555
    assert 世界.公司[1].股东排名 == [2, 1, 3, 4]


def test_交易保留16及32位回绕并拒绝超卖() -> None:
    世界 = 股市样本()
    世界.股票[0].可购股数 = 世界.股票[0].标志10 = 65535
    世界.股票[0].浮点位[2] = 浮点位(1)
    世界.玩家[0].记录.银行 = 2147483647
    股市_类.api_卖出(世界, 0, 0, 1, True)
    assert (世界.股票[0].可购股数, 世界.股票[0].标志10, 世界.玩家[0].记录.银行) == (
        0,
        0,
        -2147483648,
    )
    原 = 世界.api_导出()
    with pytest.raises(ValueError):
        股市_类.api_卖出(世界, 0, 0, 1000, True)
    assert 世界.api_导出() == 原


def test_市场买股扣银行一级发行扣现金() -> None:
    世界 = 股市样本()
    结果 = 股市_类.api_买入(世界, 0, 0, 100, True)
    assert 结果.费用 == 1555
    assert (世界.玩家[0].记录.银行, 世界.玩家[0].记录.现金) == (8445, 20000)
    assert (世界.股票[0].可购股数, 世界.股票[0].标志10) == (6500, 1400)
    世界 = 股市样本()
    世界.公司[1].估值 = 1234567
    世界.公司[1].剩余股份 = 500
    结果 = 股市_类.api_买入(世界, 0, 0, 50, False)
    assert 结果.费用 == 6150
    assert (世界.玩家[0].记录.现金, 世界.玩家[0].记录.银行, 世界.公司[1].剩余股份) == (
        13850,
        10000,
        450,
    )


def test_强制行情忽略停牌且改上一历史槽() -> None:
    世界 = 股市样本()
    世界.股票[0].停牌天数 = 5
    世界.股票[0].新闻走势 = 0x11
    世界.股票[0].浮点位[1] = 浮点位(1000)
    assert 股市_类.api_强制行情(世界, 1) == 1
    assert 世界.股票[0].浮点位[2] == 世界.股史[0][143] == 浮点位(1100)
    assert 世界.股史游标 == 0
    assert 股市_类.api_走势(世界, 0) == 走势_类.涨停


def test_财富逐股落binary32并处理负数抵消() -> None:
    世界 = 股市样本()
    for 玩家 in 世界.玩家:
        for 持仓 in 玩家.持仓:
            持仓.数量 = 0
    for 股 in 世界.股票:
        股.浮点位[2] = 0
    世界.玩家[0].记录.现金 = 16777217
    世界.玩家[0].记录.银行 = 世界.玩家[0].记录.贷款 = 0
    assert 股市_类.api_财富(世界, 0) == 16777216
    世界.玩家[0].记录.现金 = -5
    世界.玩家[0].持仓[0].数量 = 1
    世界.股票[0].浮点位[2] = 浮点位(1.5)
    assert 股市_类.api_财富(世界, 0) == -3


def test_休市保持全部股市和随机位() -> None:
    世界 = 股市样本()
