class 落点样本_类(会话落点_类, 会话地产_类, 动作样本_类):
    """
    落点/每日结算使用真实依赖，实际完整回合另由公开会话验收。

    更新日志：
    2026.10.24 - 不以测试适配器冒充图形游戏或长期对局。
    """

    def __init__(self) -> None:
        动作样本_类.__init__(self)
        self.商店, self.商店地产, self.魔法类别 = None, 0, 0
        self.互动小游戏, self.完成天数, self.待托管 = False, 0, [None] * 4


def test_事件等待选择不得提前交付处理器表现() -> None:
    会 = 落点样本_类()
    会._发事件(游戏事件种类_类.提示, "old")

    def 处理() -> None:
        会._发事件(游戏事件种类_类.提示, "handler")
        会._效果(效果种类_类.新闻影片, 0, 会._角色点(0))
        raise 待选择异常_类(决策_类(决策种类_类.卡片目标, 0), 0)

    with pytest.raises(待选择异常_类):
        会._先屏幕(处理)
    assert [事.消息 for 事 in 会.事件队列] == ["old"] and not 会.效果队列


def test_商店真实买卡扣点并刷新选项退出才返未售库存() -> None:
    会 = 落点样本_类()
    会._玩家().点券 = 9999
    会._开商店(0)
    assert 会.待决策.种类 == 决策种类_类.商店
    卡, 原 = 会.商店.卡片[0], 会._玩家().点券
    assert 会._商店行动(100 + 卡, 1)
    assert 卡 in 会._玩家().卡片 and 会._玩家().点券 < 原
    assert 会._商店行动(0, 1) and 会.商店 is None
    assert 会.阶段 == 游戏阶段_类.推进回合


@pytest.mark.parametrize("arg_类", [6, 7, 8])
def test_人类互动小游戏携带真实种子不提前产生奖励(arg_类: int) -> None:
    会 = 落点样本_类()
    会.互动小游戏 = True
    会.世界.节点[会._玩家().节点].标志 = arg_类
    原 = 会._玩家().点券
    会._落点()
    assert 会.待决策.小游戏.游戏 == arg_类 - 6
    assert 会.待决策.小游戏.种子 == 1 and 会.随机.状态 == 1 and 会._玩家().点券 == 原


