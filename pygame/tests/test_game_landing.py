def test_十五日真实分红先于彩票开奖并保留两个完整快照() -> None:
    会 = 落点样本_类()
    会.世界.头.日期 = (14, 1, 2000)
    会.世界.股票[0].标志4, 会.世界.公司[1].资金 = 1, 9000
    for 人 in 会.世界.玩家:
        人.持仓[0].数量 = 0
    会.世界.玩家[0].持仓[0].数量, 会.世界.玩家[1].持仓[0].数量 = 1, 2
    彩票_类.api_购票(会.世界, 0, 1)
    会._推进日期()
    类 = [效.种类 for 效 in 会.效果队列]
    assert 类.index(效果种类_类.股利) < 类.index(效果种类_类.彩票开奖)
    assert 会.世界.玩家[0].记录.银行 == 23000 and 会.世界.玩家[1].记录.银行 == 26000
    assert 会.完成天数 == 1 and 会.世界.头.日期 == (15, 1, 2000)


