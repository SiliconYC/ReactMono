def test_回合先刷新股票再收贷款并进入人类待命() -> None:
    会, 调用 = 移动样本_类(), []
    会._玩家().控制标志, 会._玩家().x = 1, 32
    预期, 随 = deepcopy(会.世界), 随机数_类(1)
    股市_类.api_刷新限额(预期, 随)
    会._收到期贷款 = lambda: 调用.append(会.随机.状态)
    会._开始回合()
    assert 调用 == [随.状态] and 会.随机.状态 == 随.状态
    assert 会.阶段 == 游戏阶段_类.人类待命 and 会.待决策 is None
