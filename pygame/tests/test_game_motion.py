class 移动样本_类(会话移动_类, 表现样本_类):
    """
    只观察移动对外部结算接口的调用，不替代正式会话中的落点/融资等规则。

    更新日志：
    2026.10.24 - 真实完整会话另行集成验收。
    """

    def __init__(self) -> None:
        表现样本_类.__init__(self)
        self.捕获轮次起点 = False
        self.上一回合 = [None] * 4
        self.骰面, self.剩余步, self.强制骰, self.下节点 = [], 0, None, 0
        self.落点次数, self.遭遇次数, self.银行调用 = 0, 0, []

    def _状态(self):
        return self.世界.玩家[self._当前()].状态

    def _落点(self) -> None:
        self.落点次数 += 1

    def _逐步遭遇(self) -> None:
        self.遭遇次数 += 1

    def _同步附身(self, arg_槽: int) -> None:
        for 物 in self.世界.物件:
            if 物.附身玩家 == arg_槽 + 1:
                物.节点 = self.世界.玩家[arg_槽].记录.节点

    def _开银行(self, arg_经过: bool) -> None:
        self.银行调用.append(arg_经过)


