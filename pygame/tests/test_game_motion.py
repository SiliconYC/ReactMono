def test_出场仅按x判定且实际抽两个随机数标占用并发降落伞() -> None:
    会 = 移动样本_类()
    会._玩家().x, 会._玩家().y = 1, 0
    会._按需出场()
    assert 会.随机.状态 == 1
    会._玩家().x = 0
    for 节 in 会.世界.节点:
        节.标志 = 0
    会._按需出场()
    assert 会.随机.状态 == 2524885223
    assert 会.世界.节点[会._玩家().节点].标志 & 0x100
    assert 会.效果队列[-1].种类 == 效果种类_类.降落伞


def test_出场任何候选编号超过字节便先拒绝不抽随机() -> None:
    会 = 移动样本_类()
    会._玩家().x = 0
    while len(会.世界.节点) <= 256:
        另 = deepcopy(会.世界.节点[1])
        另.标志, 另.邻居[:] = 0, [1, 0, 0, 0]
        会.世界.节点.append(另)
    with pytest.raises(RuntimeError, match="byte node ID"):
        会._按需出场()
    assert 会.随机.状态 == 1


