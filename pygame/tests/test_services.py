def test_目标按建筑数量非楼层数且零财富可以并列() -> None:
    世 = 服务样本()
    assert 服务_类.api_魔法目标(世, 1) == []
    世.地产[1].经济.业主 = 2
    世.地产[1].经济.等级 = 5
    assert 服务_类.api_魔法目标(世, 2) == [1]
    for 玩家 in 世.玩家:
        玩家.记录.现金 = 玩家.记录.银行 = 玩家.记录.贷款 = 0
        for 持仓 in 玩家.持仓:
            持仓.数量 = 0
    世.地产[1].经济.业主 = 0
    assert 服务_类.api_魔法目标(世, 0) == [0, 1, 2, 3]
    assert 服务_类.api_魔法目标(世, 3) == []
    for 玩家 in 世.玩家:
        玩家.记录.控制标志 = 0
    随机 = 随机数_类(555)
    assert 服务_类.api_电脑魔法(世, 随机, 999) is None
    assert 随机.状态 == 555
