def test_魔法依赖缺失先拒绝而且不消费随机数() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    原 = 世.api_导出()
    assert not 服务_类.api_施法(世, 随机, 0, [1], 2, 魔法回调_类())
    assert not 服务_类.api_施法(世, 随机, 0, [], 1, 魔法回调_类())
    assert 原 == 世.api_导出() and 随机.状态 == 1
    with pytest.raises(IndexError):
        服务_类.api_施法(世, 随机, 0, [4], 0, 魔法回调_类())


def test_魔法全价卖卡停留与交通道具字节回绕() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    玩家 = 世.玩家[0]
    玩家.记录.点券 = 65530
    玩家.记录.卡片[:] = [1, 2] + [0] * 13
    assert 服务_类.api_施法(世, 随机, 0, [0], 0, 魔法回调_类())
    assert 玩家.记录.点券 == 394 and not any(玩家.记录.卡片)
    玩家.状态.停留天数 = 255
    服务_类.api_施法(世, 随机, 0, [0], 3, 魔法回调_类())
    assert 玩家.状态.停留天数 == 0
    玩家.记录.交通 = 0x81
    玩家.记录.道具[:] = [0] * 15
    玩家.记录.道具[4] = 255
    服务_类.api_施法(世, 随机, 0, [0], 8, 魔法回调_类())
    assert 玩家.记录.点券 == 394
    assert (玩家.记录.交通, 玩家.记录.骰数, 玩家.记录.道具[4]) == (0, 1, 0)


def test_敌意先于防御取消和转移() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    日志 = []
    钩子 = 魔法回调_类(
        敌意=lambda p, a, n: 日志.append(("敌意", p, a, n)),
        防御=lambda p: 日志.append(("防御", p)) or (2 if p == 1 else -1),
        监狱=lambda p, n: 日志.append(("监狱", p, n)),
    )
    assert 服务_类.api_施法(世, 随机, 0, [1, 3], 2, 钩子)
    assert 日志 == [
        ("敌意", 1, 0, 世.头.物价 * 90),
        ("防御", 1),
        ("监狱", 2, 3),
        ("敌意", 3, 0, 世.头.物价 * 90),
        ("防御", 3),
    ]


