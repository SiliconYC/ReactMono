# ◕ 功能
def 服务样本() -> 世界_类:
    return 世界_类.api_从地图(合成地图())


def test_空供应不抽随机数也不访问无效玩家() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    世.卡供应[:] = [0] * 30
    世.道具供应[:] = [0] * 8
    assert 服务_类.api_随机卡(世, 随机, 999) == 0
    assert 服务_类.api_随机道具(世, 随机, 999) == 0
    assert 随机.状态 == 1
    世.道具供应[0] = 1
    世.玩家[0].记录.道具[0] = 9
    assert 服务_类.api_随机道具(世, 随机, 0) == 1
    assert 世.道具供应[0] == 1 and 世.玩家[0].记录.道具[0] == 9
    assert 随机.状态 == 1103527590


def test_人类货架无放回但未扣共享供应() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    世.玩家[0].记录.控制标志 = 1
    世.卡供应[:] = [1, 2] + [0] * 28
    店 = 服务_类.api_开店(世, 随机, 0)
    assert 店.卡片 == [2, 2, 1]
    assert 世.卡供应 == [1, 2] + [0] * 28
    assert 随机.状态 == 3295386429
    世.玩家[0].记录.点券 = 500
    assert 服务_类.api_买卡(世, 店, 0, 2)
    assert 店.卡片 == [2, 1] and 店.收入 == 2000
    assert 世.玩家[0].记录.点券 == 300 and 世.卡供应[1] == 1


def test_出售道具合计九折和重复关店只入账一次() -> None:
    世, 店 = 服务样本(), 商店_类()
    世.玩家[0].记录.点券 = 0
    世.玩家[0].记录.道具[0] = 2
    assert 服务_类.api_卖道具(世, 店, 0, 1, 2)
    assert 世.玩家[0].记录.点券 == 27 and 店.收入 == 30
    世.公司[1].资金 = 世.公司[1].资金变化 = 2147483647
    服务_类.api_关店(世, 店, 6001)
    服务_类.api_关店(世, 店, 6001)
    assert 世.公司[1].资金 == 世.公司[1].资金变化 == -2147483619
    assert not 服务_类.api_卖道具(世, 店, 0, 1)


def test_电脑按手牌槽偏好卖卡再按卡编号买回() -> None:
    世, 随机 = 服务样本(), 随机数_类(123)
