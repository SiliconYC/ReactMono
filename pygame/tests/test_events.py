def test_付款使人数降到一人仍返回预计算的全部税额() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    for 人 in 世.玩家:
        人.记录.现金 = 100
    日志 = []

    def 付款(arg_付: int, arg_收: int, arg_额: int, arg_旗: int) -> None:
        日志.append((arg_付, arg_收, arg_额, arg_旗))
        for 人 in 世.玩家[1:]:
            人.记录.控制标志 = 0

    结果 = 事件_类.api_新闻编号(世, 随机, 11, 事件回调_类(付款=付款))
    assert 日志 == [(0, -1, 5, 0)]
    assert 结果.玩家掩码 == 15 and 结果.玩家金额 == [5] * 4


