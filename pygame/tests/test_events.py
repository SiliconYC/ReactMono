# ◕ 功能
def 服务样本() -> 世界_类:
    世 = 基础样本()
    世.设施.append(设施_类(编号=1))
    return 世


def test_新闻十五只允许已建普通地产而不是只有设施() -> None:
    世 = 服务样本()
    世.地产[1].经济.等级 = 0
    世.设施[1].等级 = 3
    assert 事件_类.api_新闻可用(世, 4)
    assert not 事件_类.api_新闻可用(世, 15)
    世.地产[1].经济.等级 = 1
    assert 事件_类.api_新闻可用(世, 15)
    with pytest.raises(ValueError):
        事件_类.api_新闻可用(世, 36)


def test_命运交通重映射按完整字节且后四图无地域事件() -> None:
    世 = 服务样本()
    人 = 世.玩家[0]
    人.记录.交通 = 129
    assert 事件_类.api_命运可用(世, 0, 10) is None
    人.记录.交通 = 2
    assert 事件_类.api_命运可用(世, 0, 14) == 16
    世.头.地图, 世.头.阶段 = 3, 0
    assert 事件_类.api_命运可用(世, 0, 36) == 48
    世.头.阶段 = 1
    assert 事件_类.api_命运可用(世, 0, 36) is None


