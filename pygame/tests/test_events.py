def test_命运偷卡准入计入未活跃玩家但执行不偷() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    for 人 in 世.玩家:
        人.记录.卡片[:] = [0] * 15
    世.玩家[1].记录.卡片[0] = 3
    世.玩家[1].记录.控制标志 = 0
    世.玩家[0].记录.控制标志 = 2
    assert 事件_类.api_命运可用(世, 0, 5) == 5
    结果 = 事件_类.api_命运编号(世, 随机, 0, 5, 事件回调_类())
    assert 结果.支持 and 随机.状态 == 1 and 世.玩家[1].记录.卡片[0] == 3


def test_缺回调新闻跳过但决策异常保留游标() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    世.新闻牌堆[:] = [24, 22] + [26] * 34
    世.新闻游标 = 0
    结果 = 事件_类.api_新闻(世, 随机, 事件回调_类())
    assert 结果.事件 == 22 and 世.新闻游标 == 2 and 随机.状态 == 1
    世.新闻游标 = 0

    def 待决策(arg_股: int) -> None:
        raise RuntimeError("待真实选择")

    with pytest.raises(RuntimeError, match="待真实选择"):
        事件_类.api_新闻(世, 随机, 事件回调_类(更新股票=待决策))
    assert 世.新闻游标 == 0


