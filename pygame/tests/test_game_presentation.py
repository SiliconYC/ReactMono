# ◕ 功能
class 表现样本_类(会话表现_类, 事务样本_类):
    """
    只给原会话表现提供真实世界与必要状态的测试适配器。

    更新日志：
    2026.10.24 - 不作为正式游戏入口或虚构规则后端。
    """

    def __init__(self) -> None:
        事务样本_类.__init__(self)
        self.服装, self.服装键 = [0] * 4, [0] * 4
        self.选定卡目标, self.使用中卡, self.卡图已示 = None, None, False
        self.地产待处理 = self.已购地产 = self.地产落点 = False
        self.动画, self.待决策 = None, None

    def _当前(self) -> int:
        return self.世界.头.当前玩家

    def _玩家(self) -> 玩家记录_类:
        return self.世界.玩家[self._当前()].记录

    def _人类(self) -> bool:
        return self._玩家().控制标志 == 1

    def _实例位置(self, arg_码: int) -> 效果点_类:
        地 = self.世界.地产[arg_码 - 2000]
        return 效果点_类(地.x, 地.y)


def test_在场掩码允许强制出场但仍要求坐标和活跃() -> None:
    会 = 表现样本_类()
    人 = 会.世界.玩家[0]
    人.记录.x, 人.记录.y, 人.记录.控制标志, 人.状态.医院天数 = 1, 0, 1, 128
    assert not 会._在场(0)
    人.记录.控制标志 |= 0x20
    assert 会._在场(0)
    人.记录.x = 0
    assert not 会._在场(0)


def test_服装随完整交通或睡眠梦游输入变化而结束() -> None:
    会 = 表现样本_类()
    会.服装[0], 会.服装键[0] = 19, 会._服装键(0)
    会._刷新服装()
    assert 会.服装[0] == 19
    会.世界.玩家[0].记录.交通 ^= 128
    会._刷新服装()
    assert 会.服装[0] == 0


def test_卡道具气泡过滤缺席而原事件语音仍发出() -> None:
    会 = 表现样本_类()
    会.世界.玩家[0].状态.睡眠天数 = 1
    会._语句(0, 语句表_类.卡片, 255, 2)
    assert not 会.事件队列
    会._语音(0, 3)
    assert 会.事件队列[0].语音类别 == 3


def test_金额语音恰在门槛间抽一次共享随机数() -> None:
    会 = 表现样本_类()
    会.世界.头.物价 = 1
    会._金额语音(0, 4999, 6)
    assert 会.随机.状态 == 1 and 会.事件队列[-1].语音类别 == 8
    会._金额语音(0, 5000, 6)
    assert 会.随机.状态 == 1103527590
    会._金额语音(0, 9000, 6)
    assert 会.随机.状态 == 1103527590 and 会.事件队列[-1].语音类别 == 6


def test_免租理由按原先后且附加语音不改随机() -> None:
    会 = 表现样本_类()
    主 = 会.世界.玩家[1].状态
    主.盟友, 主.神明信息, 主.医院天数 = 1, 15, 1
    会._公告免租(主, 1, 0x11, 2001)
    assert 会.事件队列[0].公告 == 公告种类_类.免租 and 会.事件队列[0].公告号 == 0
    会._公告免租(主, 1, 0, 2001)
    assert 会.事件队列[2].公告号 == 1 and 会.事件队列[-1].语音类别 == 13
    assert 会.随机.状态 == 1


def test_卡图只显示一次且使用中卡按值保存() -> None:
    会 = 表现样本_类()
    用 = 卡片用法_类(11, 卡片目标_类(目标种类_类.地产, 2001))
    会._开始卡片(用)
    用.卡片 = 12
    会._卡图()
    会._卡图()
    assert len(会.效果队列) == 1 and 会.效果队列[0].种类 == 效果种类_类.怪兽


def test_结束回合地产停留八tick与效果交错位() -> None:
    会 = 表现样本_类()
    会._发事件(游戏事件种类_类.已购地, "购买", 100)
    会.地产落点 = True
    会._结束回合()
    assert 会.阶段 == 游戏阶段_类.推进回合 and not 会.地产落点
    assert 会.效果队列[-1].种类 == 效果种类_类.暂停
    assert 会.效果队列[-1].物件种类 == 8 and 会.效果队列[-1].事件位 == 1


def test_未支持人类提示保持原文而电脑直接结束回合() -> None:
    会 = 表现样本_类()
    会._玩家().控制标志 = 1
    会._不支持("开发者原因", 游戏阶段_类.人类待命)
    assert 会.事件队列[-1].消息 == "开发者原因" and 会.待决策.提示 == "本次事件略過。"
    assert 会.阶段 == 游戏阶段_类.等待决策
    会._玩家().控制标志 = 2
    会._不支持("开发者原因2")
    assert 会.阶段 == 游戏阶段_类.推进回合
