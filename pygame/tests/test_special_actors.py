def test_龟行到路障回调顺序而且不更换当前玩家() -> None:
    世, 随机 = 服务样本(), 随机数_类(1)
    世.节点[:] = [节点_类(), 节点_类(邻居=[2, 0, 0, 0]), 节点_类(标志=1 << 16)]
    世.物件[0].种类 = 16
    人 = 世.特殊角色[1]
    人.节点, 人.上次节点, 人.业主, 人.不活跃状态, 人.龟行天数 = 1, 0, 0, 0, 2
    日志 = []
    原玩家 = 世.头.当前玩家
    钩 = 特殊回调_类(
        移除物件=lambda n: 日志.append(("移除", n)), 步后=lambda *a: 日志.append(("步后", *a))
    )
    结果 = 特殊行动_类.api_回合(世, 随机, 5, 钩)
    assert (结果.计划步数, 结果.已走步数, 结果.停止移动) == (1, 1, True)
    assert 日志 == [("移除", 1), ("步后", 5, 2)]
    assert 世.头.当前玩家 == 原玩家


