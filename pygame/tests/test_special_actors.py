def test_状态到期高位保留本回合并在下回合清零() -> None:
    世, 随机 = 服务样本(), 随机数_类(17)
    人 = 世.特殊角色[0]
    人.不活跃状态 = 0
    人.睡眠天数, 人.梦游天数, 人.停留天数, 人.龟行天数 = 1, 129, 2, 128
    结果 = 特殊行动_类.api_回合(世, 随机, 4, 特殊回调_类())
    assert 结果.计划步数 == 0 and 随机.状态 == 17
    assert (人.睡眠天数, 人.梦游天数, 人.停留天数, 人.龟行天数) == (128, 0, 1, 0)
    特殊行动_类.api_老化(人)
    assert (人.睡眠天数, 人.停留天数) == (0, 128)
    with pytest.raises(IndexError):
        特殊行动_类.api_单步(世, 随机, 8)


