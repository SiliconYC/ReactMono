def test_转盘只支持四类神明且每十帧刷新四位() -> None:
    with pytest.raises(ValueError):
        金钱转盘_类(3)
    随机, 预期 = 随机数_类(1), 随机数_类(1)
    盘 = 金钱转盘_类(1)
    位 = [预期.api_下一个() % 10 * 2 + 1 for _ in range(4)]
    盘.api_步进(随机)
    assert 盘.数字 == [位[0], *((n + 1) % 20 for n in 位[1:])]
    assert 随机.状态 == 预期.状态 and 盘.阶段 == 1
    for _ in range(9):
        盘.api_步进(随机)
    assert 随机.状态 == 预期.状态
    盘.api_步进(随机)
    for _ in range(4):
        预期.api_下一个()
    assert 随机.状态 == 预期.状态


def test_手动不停则不自动结束而电脑逐位减速后冻结() -> None:
    盘, 随机 = 金钱转盘_类(2), 随机数_类(12)
    for _ in range(200):
        盘.api_步进(随机)
    assert 盘.阶段 == 1
    盘.api_停止()
    assert 盘.阶段 == 2
    盘.api_步进(随机)
    assert 盘.阶段 == 3
    for _ in range(1000):
        if 盘.完成:
            break
        盘.api_步进(随机)
    assert 盘.完成 and all(n % 2 == 0 for n in 盘.数字)
    原 = (盘.数字.copy(), 盘.金额, 随机.状态)
    盘.api_停止()
    盘.api_步进(随机, True)
    assert 原 == (盘.数字, 盘.金额, 随机.状态)
    assert 神明_类.api_自动金额(1, 随机数_类(12)) < 1000


